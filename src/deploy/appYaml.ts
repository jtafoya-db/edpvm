/**
 * Generate the staged `databricks-app/app.yaml` from the RESOLVED bundle config.
 *
 * Why: a modern CLI `bundle deploy` uploads the app source (with the committed
 * app.yaml, which carries production defaults only) and sends the target's
 * `config.command` / `config.env` in the Apps deployment request. GovCloud's
 * Apps service ignored those request fields, so the app ran with the committed
 * app.yaml: no VITE_DATA_BACKEND or EDP_CLIENT_MINIFIED, so serve.mjs exited
 * and every request failed. scripts/deploy.sh now overwrites the staged
 * app.yaml with what `bundle validate -o json` resolved for the target (and
 * puts the committed copy back when it exits), so the uploaded file alone
 * starts the app correctly whether or not the platform honors deployment env.
 *
 * The YAML is rendered in a small block subset (every scalar double-quoted with
 * JSON escaping, which YAML reads the same) and read back by `parseAppYaml`,
 * which accepts only that subset and the committed file's plain scalars.
 * Dependency-free so `node scripts/app-yaml.ts` runs it without node_modules.
 */

export interface AppYamlEnvEntry {
  name: string;
  value?: string;
  valueFrom?: string;
}

export interface AppYamlConfig {
  command: string[];
  env: AppYamlEnvEntry[];
}

export interface BuildInfo {
  dataBackend?: unknown;
  minified?: unknown;
}

export class AppYamlError extends Error {}

export const EXPECTED_COMMAND = ["node", "serve.mjs"];
/** serve.mjs exits without these; the platform must get them from app.yaml or the deployment. */
export const REQUIRED_RUNTIME_ENV = ["VITE_DATA_BACKEND", "EDP_CLIENT_MINIFIED"] as const;

const scalar = (value: unknown): string | undefined =>
  typeof value === "string"
    ? value
    : typeof value === "number" || typeof value === "boolean"
      ? String(value)
      : undefined;

/** `resources.apps.edp_vending_machine.config` -> app.yaml's command and env. */
export function appYamlFromBundle(validateJson: unknown): AppYamlConfig {
  const app = (validateJson as { resources?: { apps?: Record<string, unknown> } })?.resources
    ?.apps?.["edp_vending_machine"] as
    { config?: { command?: unknown; env?: unknown } } | undefined;
  if (!app || typeof app !== "object") {
    throw new AppYamlError("bundle validate has no resources.apps.edp_vending_machine.");
  }
  const config = app.config;
  if (!config || typeof config !== "object") {
    throw new AppYamlError("resources.apps.edp_vending_machine has no resolved config.");
  }
  const { command: rawCommand, env: rawEnv = [] } = config;
  if (!Array.isArray(rawCommand) || rawCommand.length === 0) {
    throw new AppYamlError("the resolved app config has no command.");
  }
  const command = rawCommand.map((part, index) => {
    const text = scalar(part);
    if (text === undefined) throw new AppYamlError(`command[${index}] is not a string.`);
    return text;
  });
  if (!Array.isArray(rawEnv)) throw new AppYamlError("the resolved app config env is not a list.");
  const env = rawEnv.map((raw, index): AppYamlEnvEntry => {
    const entry = (raw ?? {}) as { name?: unknown; value?: unknown; value_from?: unknown };
    const name = scalar(entry.name);
    if (!name) throw new AppYamlError(`env[${index}] has no name.`);
    const value = scalar(entry.value);
    const valueFrom = scalar(entry.value_from);
    if (value !== undefined && valueFrom === undefined) return { name, value };
    if (valueFrom !== undefined && value === undefined) return { name, valueFrom };
    throw new AppYamlError(
      `env ${name} must have exactly one of value or value_from in the resolved config.`,
    );
  });
  return { command, env };
}

const quote = (text: string) => JSON.stringify(text);

export function renderAppYaml(config: AppYamlConfig): string {
  const lines = [
    "# GENERATED by scripts/deploy.sh from `databricks bundle validate -o json` for the",
    "# target being deployed (src/deploy/appYaml.ts). Do not edit: the committed",
    "# databricks-app/app.yaml is restored when the deploy exits.",
    "command:",
    ...config.command.map((part) => `  - ${quote(part)}`),
    "env:",
  ];
  for (const entry of config.env) {
    lines.push(`  - name: ${quote(entry.name)}`);
    if (entry.valueFrom !== undefined) lines.push(`    valueFrom: ${quote(entry.valueFrom)}`);
    else lines.push(`    value: ${quote(entry.value ?? "")}`);
  }
  return lines.join("\n") + "\n";
}

function readScalar(raw: string, lineNumber: number): string {
  const text = raw.trim();
  if (text.startsWith('"')) {
    try {
      const parsed: unknown = JSON.parse(text);
      if (typeof parsed === "string") return parsed;
    } catch {
      // fall through to the error below
    }
    throw new AppYamlError(`line ${lineNumber}: unreadable quoted string ${text}`);
  }
  if (text === "" || /^['[{&*!|>%@`]/.test(text) || / #/.test(text)) {
    throw new AppYamlError(`line ${lineNumber}: unsupported YAML scalar ${text || "(empty)"}`);
  }
  return text;
}

/** Read app.yaml in the subset renderAppYaml writes (and the committed file uses). */
export function parseAppYaml(text: string): AppYamlConfig {
  const config: AppYamlConfig = { command: [], env: [] };
  let section: "command" | "env" | undefined;
  let entry: AppYamlEnvEntry | undefined;
  const lines = text.split(/\r?\n/);
  for (const [index, line] of lines.entries()) {
    const n = index + 1;
    if (/^\s*(#.*)?$/.test(line)) continue;
    let match: RegExpMatchArray | null;
    if ((match = line.match(/^(command|env):\s*$/))) {
      section = match[1] as "command" | "env";
      entry = undefined;
    } else if (section === "command" && (match = line.match(/^ {2}- (.+)$/))) {
      config.command.push(readScalar(match[1]!, n));
    } else if (section === "env" && (match = line.match(/^ {2}- name: (.+)$/))) {
      entry = { name: readScalar(match[1]!, n) };
      config.env.push(entry);
    } else if (
      section === "env" &&
      entry &&
      (match = line.match(/^ {4}(value|valueFrom): (.+)$/))
    ) {
      const key = match[1] as "value" | "valueFrom";
      if (entry.value !== undefined || entry.valueFrom !== undefined) {
        throw new AppYamlError(`line ${n}: env ${entry.name} has more than one value.`);
      }
      entry[key] = readScalar(match[2]!, n);
    } else {
      throw new AppYamlError(`line ${n}: not in the app.yaml subset this deploy reads: ${line}`);
    }
  }
  return config;
}

/** Problems that make the staged app.yaml unsafe to upload; empty when it's fine. */
export function checkStagedAppYaml(text: string, buildInfo: unknown): string[] {
  let config: AppYamlConfig;
  try {
    config = parseAppYaml(text);
  } catch (error) {
    return [`app.yaml: ${(error as Error).message}`];
  }
  const problems: string[] = [];
  if (JSON.stringify(config.command) !== JSON.stringify(EXPECTED_COMMAND)) {
    problems.push(
      `app.yaml command is ${JSON.stringify(config.command)}, not ${JSON.stringify(EXPECTED_COMMAND)}.`,
    );
  }
  const seen = new Map<string, AppYamlEnvEntry>();
  for (const entry of config.env) {
    if (seen.has(entry.name)) problems.push(`app.yaml sets env ${entry.name} more than once.`);
    seen.set(entry.name, entry);
    if (entry.value === undefined && entry.valueFrom === undefined) {
      problems.push(`app.yaml env ${entry.name} has neither value nor valueFrom.`);
    }
  }
  const build = buildInfo as BuildInfo | null;
  if (!build || typeof build !== "object") {
    problems.push("build-info.json is missing or not an object; cannot check app.yaml against it.");
    return problems;
  }
  const expected: Record<(typeof REQUIRED_RUNTIME_ENV)[number], string> = {
    VITE_DATA_BACKEND: String(build.dataBackend),
    EDP_CLIENT_MINIFIED: String(build.minified),
  };
  for (const name of REQUIRED_RUNTIME_ENV) {
    const entry = seen.get(name);
    if (!entry || entry.value === undefined) {
      problems.push(
        `app.yaml has no ${name} value; serve.mjs refuses to start without it (build-info.json says ${expected[name]}).`,
      );
    } else if (entry.value !== expected[name]) {
      problems.push(
        `app.yaml sets ${name}=${entry.value}, but build-info.json records ${expected[name]}.`,
      );
    }
  }
  return problems;
}
