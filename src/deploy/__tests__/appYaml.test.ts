// @vitest-environment node
/**
 * The staged app.yaml generator (seam: src/deploy/appYaml.ts).
 *
 * GovCloud's Apps service ignored the command/env_vars the CLI sends in the
 * deployment request, so the app ran with the committed app.yaml and serve.mjs
 * exited. The staged app.yaml is now generated from the RESOLVED bundle config,
 * so it's self-sufficient whether or not the platform honors deployment env.
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { load } from "js-yaml";
import { describe, expect, it } from "vitest";

import { appYamlFromBundle, checkStagedAppYaml, parseAppYaml, renderAppYaml } from "../appYaml.ts";

const validate = (env: unknown[], command: unknown = ["node", "serve.mjs"]) => ({
  bundle: { target: "govdev" },
  resources: { apps: { edp_vending_machine: { name: "edp-vm-test", config: { command, env } } } },
});

const GOVDEV_ENV = [
  { name: "NODE_ENV", value: "production" },
  { name: "EIR_MAX_UPLOAD_BYTES", value: 10485760 },
  { name: "EDP_SLA_HOLIDAYS", value: "[]" },
  { name: "EDP_ACCESS_REQUEST_SLA_PROVISIONAL", value: true },
  { name: "VITE_DATA_BACKEND", value: "delta" },
  { name: "EDP_CLIENT_MINIFIED", value: "false" },
  { name: "EDP_SAMPLE: odd # value", value: 'a "quoted" # not a comment' },
  { name: "DATABRICKS_WAREHOUSE_ID", value_from: "sql-warehouse" },
];
const BUILD = { dataBackend: "delta", minified: false, commit: "abc", builtAt: "now" };

describe("appYamlFromBundle", () => {
  it("takes command and env from the resolved app config, as strings, value_from -> valueFrom", () => {
    expect(appYamlFromBundle(validate(GOVDEV_ENV))).toEqual({
      command: ["node", "serve.mjs"],
      env: [
        { name: "NODE_ENV", value: "production" },
        { name: "EIR_MAX_UPLOAD_BYTES", value: "10485760" },
        { name: "EDP_SLA_HOLIDAYS", value: "[]" },
        { name: "EDP_ACCESS_REQUEST_SLA_PROVISIONAL", value: "true" },
        { name: "VITE_DATA_BACKEND", value: "delta" },
        { name: "EDP_CLIENT_MINIFIED", value: "false" },
        { name: "EDP_SAMPLE: odd # value", value: 'a "quoted" # not a comment' },
        { name: "DATABRICKS_WAREHOUSE_ID", valueFrom: "sql-warehouse" },
      ],
    });
  });

  it.each([
    ["no app", { resources: {} }, /edp_vending_machine/],
    ["no config", { resources: { apps: { edp_vending_machine: {} } } }, /config/],
    ["no command", validate(GOVDEV_ENV, null), /command/],
    [
      "a value-less entry",
      validate([...GOVDEV_ENV, { name: "EDP_ADMIN_GROUP_ID" }]),
      /EDP_ADMIN_GROUP_ID/,
    ],
    ["a nameless entry", validate([...GOVDEV_ENV, { value: "x" }]), /name/],
  ])("refuses %s", (_label, json, message) => {
    expect(() => appYamlFromBundle(json)).toThrow(message);
  });
});

describe("renderAppYaml / parseAppYaml", () => {
  it("renders YAML that a real YAML parser reads back as the same config", () => {
    const config = appYamlFromBundle(validate(GOVDEV_ENV));
    const text = renderAppYaml(config);
    expect(load(text)).toEqual(config);
    expect(parseAppYaml(text)).toEqual(config);
    // CRLF (a Windows checkout or editor) reads the same.
    expect(parseAppYaml(text.replace(/\n/g, "\r\n"))).toEqual(config);
  });

  it("says it's generated, so nobody hand-edits the staged copy", () => {
    expect(renderAppYaml(appYamlFromBundle(validate(GOVDEV_ENV)))).toMatch(
      /^# GENERATED by scripts\/deploy\.sh/,
    );
  });

  it("reads the committed app.yaml the way js-yaml does", () => {
    const text = readFileSync(join(process.cwd(), "databricks-app/app.yaml"), "utf8");
    expect(parseAppYaml(text)).toEqual(load(text));
  });

  it("refuses YAML outside the subset it renders, instead of guessing", () => {
    expect(() => parseAppYaml("command: [node, serve.mjs]\n")).toThrow(/line 1/);
  });
});

describe("checkStagedAppYaml", () => {
  const staged = (env: unknown[]) => renderAppYaml(appYamlFromBundle(validate(env)));

  it("passes a generated file that matches build-info.json", () => {
    expect(checkStagedAppYaml(staged(GOVDEV_ENV), BUILD)).toEqual([]);
  });

  it("fails the committed app.yaml for govdev: it has no VITE_DATA_BACKEND or EDP_CLIENT_MINIFIED", () => {
    const text = readFileSync(join(process.cwd(), "databricks-app/app.yaml"), "utf8");
    const problems = checkStagedAppYaml(text, BUILD);
    expect(problems.join("\n")).toMatch(/VITE_DATA_BACKEND/);
    expect(problems.join("\n")).toMatch(/EDP_CLIENT_MINIFIED/);
  });

  it("fails when the env disagrees with how the server was built", () => {
    expect(checkStagedAppYaml(staged(GOVDEV_ENV), { ...BUILD, dataBackend: "memory" })).toEqual([
      expect.stringMatching(/VITE_DATA_BACKEND=delta.*build-info\.json.*memory/),
    ]);
    expect(checkStagedAppYaml(staged(GOVDEV_ENV), { ...BUILD, minified: true })).toEqual([
      expect.stringMatching(/EDP_CLIENT_MINIFIED=false.*build-info\.json.*true/),
    ]);
  });

  it("fails a duplicate env name and a command that isn't node serve.mjs", () => {
    const dup = staged([...GOVDEV_ENV, { name: "NODE_ENV", value: "development" }]);
    expect(checkStagedAppYaml(dup, BUILD).join("\n")).toMatch(/NODE_ENV.*more than once/);
    const npm = renderAppYaml({
      ...appYamlFromBundle(validate(GOVDEV_ENV)),
      command: ["npm", "start"],
    });
    expect(checkStagedAppYaml(npm, BUILD).join("\n")).toMatch(/command/);
  });

  it("fails an unreadable file or build-info.json", () => {
    expect(checkStagedAppYaml("command: [x]\n", BUILD).join("\n")).toMatch(/line 1/);
    expect(checkStagedAppYaml(staged(GOVDEV_ENV), null).join("\n")).toMatch(/build-info/);
  });
});
